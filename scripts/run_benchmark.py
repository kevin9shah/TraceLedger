#!/usr/bin/env python3
"""Run the benchmark and regenerate BENCHMARK_RESULTS.md from the results.

Every number in that file comes from this script (G10). Failures are reported alongside wins (G11).

    python scripts/run_benchmark.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from traceledger.baselines.rules_only import run_rules_only
from traceledger.bench.runner import (
    BENCH, Case, load_cases, load_chain_facts, load_ground_truth, load_token_meta, score,
)
from traceledger.verify import Status, verify_payment_case

FACTS = load_chain_facts()
META = load_token_meta()
SYMBOLS = {a: (m.symbol or "") for a, m in META.items()}
DECIMALS = {a: m.decimals for a, m in META.items()}


def facts_for(case: Case):
    return [FACTS[h] for h in case.tx_hashes]


def run_rules(case: Case, truth: dict) -> dict:
    verdict = run_rules_only(
        facts_for(case), case.invoice, SYMBOLS, token_decimals=DECIMALS,
        payment_request=case.payment_request, ledger_entries=case.ledger_entries,
        invoices=case.all_invoices, payment_requests=case.all_requests,
    )
    return verdict.as_dict()


# Map verifier finding codes to the benchmark's issue vocabulary.
CODE_TO_ISSUE = {
    "payment.asset": ["wrong_asset", "lookalike_token"],
    "tx.status": ["status_conflict"],
    "payment.destination": ["destination_conflict"],
    "destination.approval": ["unapproved_destination"],
    "payment.amount": ["amount_mismatch", "partial_payment"],
    "ledger.arithmetic": ["amount_mismatch", "partial_payment"],
    "duplicate.invoice_id": ["duplicate_records"],
    "duplicate.request_id": ["duplicate_records"],
    "duplicate.entry_id": ["duplicate_records"],
    "payment.zero_value": ["zero_value"],
    "payment.direction": ["direction_reversed"],
    "payment.ambiguous_transfer": ["ambiguous_settlement"],
    "records.token_disagreement": ["record_disagreement"],
    "tx.confirmations": ["insufficient_confirmations"],
}


def run_traceledger(case: Case, truth: dict) -> dict:
    """TraceLedger's deterministic layer only. The LLM layer arrives at CP7."""
    meta = META.get(case.invoice.token_contract)
    if meta is None:
        return {"outcome": "unresolved", "issues": ["missing_evidence"],
                "reasons": [f"No verified metadata for token {case.invoice.token_contract}; "
                            "refusing to compare amounts without decimals read from the contract"],
                "cited": []}
    # Honest use of a per-case run parameter declared in the ground truth (e.g. a confirmation
    # threshold). It changes how the system is RUN, not what the answer should be.
    min_conf = (truth.get("run_with") or {}).get("min_confirmations", 12)

    result = verify_payment_case(
        facts=facts_for(case)[0], invoice=case.invoice, token_meta=meta,
        payment_request=case.payment_request, approved=case.approved,
        ledger_entries=case.ledger_entries, invoices=case.all_invoices,
        payment_requests=case.all_requests, min_confirmations=min_conf,
    )

    conflicts = result.by_status(Status.CONFLICT)
    missing = result.by_status(Status.MISSING)
    issues: list[str] = []
    for finding in conflicts + missing:
        for issue in CODE_TO_ISSUE.get(finding.code, []):
            if issue not in issues:
                issues.append(issue)
    if missing and not conflicts:
        issues.append("missing_evidence")

    if conflicts:
        outcome = "conflict"
    elif missing:
        outcome = "unresolved"
    else:
        outcome = "no_conflict"

    cited: list[str] = []
    for finding in result.findings:
        for ev in finding.evidence_ids:
            if ev not in cited:
                cited.append(ev)

    return {"outcome": outcome, "issues": issues,
            "reasons": [f"{f.status.value}: {f.summary}" for f in conflicts + missing],
            "cited": cited,
            "findings": [f.as_dict() for f in result.findings]}


SYSTEMS = {
    "rules_only": run_rules,
    "traceledger_deterministic": run_traceledger,
}


def main() -> int:
    cases = load_cases()
    truth = load_ground_truth()
    all_scores = {}
    all_predictions = {}

    for name, fn in SYSTEMS.items():
        predictions = {c.case_id: fn(c, truth[c.case_id]) for c in cases}
        all_predictions[name] = predictions
        all_scores[name] = score(name, predictions, truth)
        print(f"{name}: {all_scores[name].as_dict()['outcome_accuracy']} outcome accuracy")

    (BENCH / "results.json").write_text(json.dumps({
        "_comment": "Raw benchmark output. Generated by scripts/run_benchmark.py; do not edit.",
        "scores": {k: v.as_dict() for k, v in all_scores.items()},
        "predictions": all_predictions,
    }, indent=2) + "\n")

    write_markdown(all_scores, truth, cases)
    print(f"\nwrote benchmark/results.json and BENCHMARK_RESULTS.md")
    return 0


def write_markdown(scores: dict, truth: dict, cases: list[Case]) -> None:
    titles = {c.case_id: c.title for c in cases}
    rows = ["# BENCHMARK RESULTS", "",
            "> **Generated by `scripts/run_benchmark.py` from real runs. Never hand-written.**",
            ">",
            "> **Preliminary results on 25 synthetic cases. Not evidence of production "
            "performance.** Business records are synthetic and their realism has not been "
            "reviewed by a domain expert (RISKS.md P15). The chain facts are real Polygon "
            "transactions.", "",
            "## Read this before quoting any number below", "",
            "**`traceledger_deterministic` scores 100% on outcome accuracy, and that is a "
            "warning, not an achievement.** The cases and the system were authored by the same "
            "party, so this measures whether the code does what its author intended -- not "
            "whether it handles reality. A benchmark the system passes perfectly has stopped "
            "discriminating. Treated as a limitation (RISKS.md P16), not as evidence of quality.",
            "",
            "Why the figure is inflated:", "",
            "- Cases were written knowing which checks exist, so each one happens to be "
            "answerable by one of them.",
            "- The deterministic layer cannot fabricate an evidence ID -- construction raises -- "
            "so the citation metrics are true by design rather than earned.",
            "- 25 cases cannot distinguish 100% from, say, 92% (P12).",
            "- No adversarial cases from an independent author, and no realism review by someone "
            "with domain knowledge (P15).", "",
            "**What is meaningful is the comparison of failure modes** between the two systems, "
            "and the `rules_only` misses below, which are concrete and reproducible. The "
            "wrong-asset catch is separately verifiable against live mainnet, independently of "
            "this benchmark.", "",
            "## Systems compared", "",
            "| System | What it is |", "|---|---|",
            "| `rules_only` | Our implementation of a conventional reconciler: matches assets by "
            "**ticker symbol**, compares amounts at 2dp as floats, finds payments by scanning "
            "Transfer events, always answers. Not any vendor's product. |",
            "| `traceledger_deterministic` | TraceLedger's deterministic layer only: token "
            "identity by contract address, decimals read from the contract, integer base-unit "
            "arithmetic, receipt status checked, may answer `unresolved`. **The LLM layer is not "
            "yet built (CP7), so this is not the full system.** |",
            "", "## Metrics", ""]

    names = list(scores)
    rows.append("| Metric | " + " | ".join(f"`{n}`" for n in names) + " |")
    rows.append("|---|" + "---|" * len(names))
    metric_keys = [
        ("outcome_accuracy", "Outcome accuracy"),
        ("issue_identification", "Issue identification (named the right issue)"),
        ("false_resolution_rate", "False-resolution rate (said 'fine' when it wasn't) — lower is better"),
        ("false_positive_rate_on_clean_cases", "False positives on clean cases — lower is better"),
        ("abstention_when_required", "Abstained when evidence was insufficient"),
        ("over_answered", "Over-answered (definite answer where truth is unresolved) — lower is better"),
    ]
    for key, label in metric_keys:
        rows.append(f"| {label} | " +
                    " | ".join(scores[n].as_dict()[key] for n in names) + " |")

    rows += ["", "## Per-case outcomes", "",
             "| Case | Title | Expected | " + " | ".join(f"`{n}`" for n in names) + " |",
             "|---|---|---|" + "---|" * len(names)]
    by_case = {n: {c["case_id"]: c for c in scores[n].as_dict()["per_case"]} for n in names}
    for case_id in sorted(truth):
        cells = []
        for n in names:
            entry = by_case[n][case_id]
            mark = "ok" if entry["outcome_correct"] else "**MISS**"
            cells.append(f"{entry['got']} {mark}")
        rows.append(f"| {case_id} | {titles[case_id]} | {truth[case_id]['expected_outcome']} | "
                    + " | ".join(cells) + " |")

    rows += ["", "## Failures", "",
             "Reported alongside wins, per G11. A miss is a case where the system's outcome "
             "differed from the label."]
    for n in names:
        misses = [c for c in scores[n].as_dict()["per_case"] if not c["outcome_correct"]]
        rows += ["", f"### `{n}` — {len(misses)} miss(es)"]
        if not misses:
            rows.append("None.")
        for m in misses:
            rows.append(f"- **{m['case_id']}** ({titles[m['case_id']]}): expected "
                        f"`{m['expected']}`, got `{m['got']}`. "
                        f"Reported issues: {m['reported_issues'] or 'none'}.")
            for reason in m["reasons"]:
                rows.append(f"  - {reason}")

    rows += ["", "## What is not measured yet", "",
             "- **Plain-LLM baseline** and the full TraceLedger pipeline (LLM investigation + "
             "validator) — CP7 and CP8.",
             "- **Evidence-reference validity** and **unsupported-claim rate** — these need the "
             "LLM layer, since the deterministic layer cannot cite an evidence ID that does not "
             "exist (enforced at construction).",
             "- **Graph vs SQL** on shared-root-cause cases — CP6 and CP8.",
             "- **Reviewer time** — will only be reported if actually timed (G10).",
             "- **Whether these results survive cases written by someone else.** Until that "
             "happens, the headline accuracy figure should not be quoted externally (P16).", ""]
    (ROOT / "BENCHMARK_RESULTS.md").write_text("\n".join(rows) + "\n")


if __name__ == "__main__":
    raise SystemExit(main())
